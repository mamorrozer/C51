/*------------------------------------------------------------
 * 文件：delay.c
 * 作用：提供基于空循环的阻塞延时实现。
 * 框架：DelayMs() 按毫秒循环，每毫秒内部执行校准过的双重循环。
 * 说明：该延时会占用 CPU，适用于初始化阶段或短等待，不适合长时任务调度。
 *-----------------------------------------------------------*/
#include <REGX52.H>
#include "delay.h"

void DelayMs(unsigned int ms)
{
    unsigned char i, j;
    /* 该延时参数基于 11.0592MHz 晶振经验值校准。 */
    while (ms--)
    {
        i = 2;
        j = 239;
        do
        {
            while (--j);
        } while (--i);
    }
}
